// Regenerates README.md from data/profile.json. Each card's <img title> carries the details its
// hover interaction reveals, because GitHub renders README SVGs as static images.
// Usage: node scripts/readme.mjs
import { readFile, writeFile } from "node:fs/promises";

const root = new URL("../", import.meta.url);
const profile = JSON.parse(await readFile(new URL("data/profile.json", root), "utf8"));
const RAW = "https://raw.githubusercontent.com/gowtham-dd/gowtham-dd/output";

const attr = (s) => s.replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

function card({ name, alt, tooltip, caption }) {
  const title = attr([...tooltip.filter(Boolean), "↗ Click to open the interactive version."].join("\n"));
  return `<a href="${RAW}/${name}-full.svg">
<picture>
  <source media="(prefers-color-scheme: dark)" srcset="${RAW}/${name}-dark.svg" />
  <source media="(prefers-color-scheme: light)" srcset="${RAW}/${name}-light.svg" />
  <img width="100%" alt="${attr(alt)}" title="${title}" src="${RAW}/${name}-dark.svg" />
</picture>
</a>${caption ? `\n<p align="center"><sub>${caption}</sub></p>` : ""}

<br/>
`;
}

const { about, hackathons, projects, stack, experience } = profile;
const linked = projects.filter((p) => p.url);

const cards = [
  card({
    name: "calendar-3d",
    alt: "3D contribution calendar for the last 12 months",
    tooltip: ["CONTRIBUTIONS · LAST 12 MONTHS", "Taller, brighter blocks = busier days."],
    caption: "Hover any card for its details · click to open it full-screen and explore.",
  }),
  card({
    name: "about",
    alt: `About: ${about.whoami}`,
    tooltip: ["ABOUT", about.whoami, ...about.rows.map((r) => `${r.key}: ${r.value} (${r.note})`)],
  }),
  card({
    name: "hackathons",
    alt: `Hackathons: ${hackathons.map((h) => `${h.result} ${h.short} (${h.year})`).join(", ")}`,
    tooltip: ["HACKATHONS & WINS", ...hackathons.map((h) => `${h.result} · ${h.event} — ${h.venue}, ${h.year}`)],
  }),
  card({
    name: "work",
    alt: `Selected work: ${projects.map((p) => p.title).join(", ")}`,
    tooltip: ["SELECTED WORK", ...projects.flatMap((p, k) => [`${String(k + 1).padStart(2, "0")} ${p.title} — ${p.description}`, `    ${p.stack.join(" · ")}`])],
    caption: linked.map((p) => `<a href="${p.url}">${p.title}</a>`).join(" · "),
  }),
  card({
    name: "experience",
    alt: `Experience: ${experience.map((e) => `${e.role} @ ${e.org}`).join(", ")}`,
    tooltip: ["EXPERIENCE & IMPACT", ...experience.map((e) => `${e.role} @ ${e.org} (${e.period}): ${e.impact}`)],
  }),
  card({
    name: "stack",
    alt: `Tech arsenal: ${stack.map((g) => g.items.join(", ")).join(", ")}`,
    tooltip: ["TECH ARSENAL", ...stack.map((g) => `${g.name}: ${g.items.join(", ")}`)],
  }),
  card({
    name: "languages",
    alt: "Languages by code share, plus public repos, projects shipped, and hackathon wins",
    tooltip: ["CODE & NUMBERS", "Code share across public repos, refreshed automatically."],
  }),
];

